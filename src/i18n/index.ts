export const dicts: Record<Lang, Dict> = { "zh-CN": zhCN, en, "zh-TW": zhTW };

export function getLang(): Lang {
  try {
    const v = localStorage.getItem("abc-lang") as Lang | null;
    return v && v in dicts ? v : "zh-CN";
  } catch {
    return "zh-CN";
  }
}

/** 翻译函数：t("key") / t("key", {name}) */
export function t(key: string, vars?: Record<string, string | number>): string {
  const d = dicts[getLang()] ?? zhCN;
  let s = d[key] ?? zhCN[key] ?? key;
  if (vars) {
    for (const k in vars) s = s.replaceAll(`{${k}}`, String(vars[k]));
  }
  return s;
}
